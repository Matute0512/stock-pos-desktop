
CREATE TABLE CATEGORY(
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL UNIQUE,
    ACTIVE BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE PRODUCT(
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SKU VARCHAR(40),
    BARCODE VARCHAR(40),
    NAME VARCHAR(160) NOT NULL,
    DESCRIPTION VARCHAR(255),
    CATEGORY_ID BIGINT,
    COST DECIMAL(14,2) NOT NULL DEFAULT 0,
    PRICE DECIMAL(14,2) NOT NULL DEFAULT 0,
    STOCK_QTY DECIMAL(14,3) NOT NULL DEFAULT 0,
    MIN_STOCK_QTY DECIMAL(14,3) NOT NULL DEFAULT 0,
    ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PRODUCT_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(ID),
    CONSTRAINT UQ_PRODUCT_BARCODE UNIQUE (BARCODE)
);

CREATE TABLE STOCK_MOVEMENT(
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID BIGINT NOT NULL,
    MOVEMENT_TYPE VARCHAR(20) NOT NULL,
    QUANTITY DECIMAL(14,3) NOT NULL,
    RESULT_STOCK_QTY DECIMAL(14,3) NOT NULL,
    REFERENCE_TYPE VARCHAR(20),
    REFERENCE_ID BIGINT,
    REASON VARCHAR(255),
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_STOCK_MOVEMENT_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(ID),
    CONSTRAINT CHK_STOCK_MOVEMENT_TYPE CHECK (
        MOVEMENT_TYPE IN (
                        'INITIAL',
                        'PURCHASE',
                        'SALE',
                         'RETURN'
                         'ADJUST_IN'
                         'ADJUST_OUT'
        )
    )
);

CREATE TABLE SALE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SALE_NUMBER VARCHAR(30) NOT NULL UNIQUE,
    SALE_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    SUBTOTAL DECIMAL(14,2) NOT NULL DEFAULT 0,
    DISCOUNT_AMOUNT DECIMAL(14,2) NOT NULL DEFAULT 0,
    TOTAL DECIMAL(14,2) NOT NULL DEFAULT 0,
    PAYMENT_METHOD VARCHAR(20) NOT NULL,
    CASH_RECEIVED DECIMAL(14,2),
    CHANGE_AMOUNT DECIMAL(14,2),
    STATUS VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',
    NOTES VARCHAR(255),
    CONSTRAINT CHK_SALE_PAYMENT_METHOD CHECK (
        PAYMENT_METHOD IN (
                           'CASH',
                           'CARD',
                           'TRANSFER',
                           'OTHER'
        )
    ),
    CONSTRAINT CHK_SALE_STATUS CHECK (
       STATUS IN (
                  'COMPLETED',
                  'CANCELLED',
                  'REFUNDED'
       )
    )
);

CREATE TABLE SALE_ITEM(
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SALE_ID BIGINT NOT NULL,
    PRODUCT_ID BIGINT,
    PRODUCT_NAME VARCHAR(160) NOT NULL,
    QUANTITY DECIMAL(14,3) NOT NULL,
    UNIT_PRICE DECIMAL(14,3) NOT NULL,
    LINE_TOTAL DECIMAL(14,2) NOT NULL,
    CONSTRAINT FK_SALE_ITEM_SALE FOREIGN KEY (SALE_ID) REFERENCES SALE(ID),
    CONSTRAINT FK_SALE_ITEM_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(ID)
);

CREATE TABLE SETTING (
    SETTING_KEY VARCHAR(60) PRIMARY KEY,
    SETTING_VALUE VARCHAR(255) NOT NULL
);

MERGE INTO SETTING (SETTING_KEY, SETTING_VALUE)
KEY (SETTING_KEY)
VALUES('SALE_NUMBER_NEXT', 1);

CREATE INDEX IDX_PRODUCT_NAME ON PRODUCT(NAME);
CREATE INDEX IDX_PRODUCT_BARCODE ON PRODUCT(BARCODE);
CREATE INDEX IDX_PRODUCT_ACTIVE ON PRODUCT(ACTIVE);
CREATE INDEX IDX_PRODUCT_CATEGORY ON PRODUCT(CATEGORY_ID);

CREATE INDEX IDX_STOCK_MOVEMENT_PRODUCT ON STOCK_MOVEMENT(PRODUCT_ID);
CREATE INDEX IDX_STOCK_MOVEMENT_DATE ON STOCK_MOVEMENT(CREATED_AT);

CREATE INDEX IDX_SALE_ITEM_SALE ON SALE_ITEM(SALE_ID);
CREATE INDEX IDX_SALE_ITEM_PRODUCT ON SALE_ITEM(PRODUCT_ID);

